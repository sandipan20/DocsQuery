"""
DocsQuery - Answer Correctness

Provides a lightweight semantic similarity signal between a
generated answer and a reference answer.

IMPORTANT:
This is only one signal for answer correctness.

It does NOT prove that an answer is factually correct.

We will later combine it with:

    - groundedness
    - citation coverage
    - citation validity
    - optional LLM-based judging
"""

import math


def cosine_similarity(
    left: list[float],
    right: list[float],
) -> float:
    """
    Calculate cosine similarity between two vectors.

    Cosine similarity measures how similar two vectors are
    based on their direction.

    Args:
        left:
            First embedding vector.

        right:
            Second embedding vector.

    Returns:
        Cosine similarity between -1.0 and 1.0.

    Raises:
        ValueError:
            If vector dimensions differ or either vector is
            a zero vector.
    """

    # Both vectors must have the same dimensionality.
    if len(left) != len(right):
        raise ValueError("Vectors must have the same dimension.")

    # Calculate the magnitude of each vector.
    left_norm = math.sqrt(sum(value * value for value in left))

    right_norm = math.sqrt(sum(value * value for value in right))

    # A zero vector cannot be normalized.
    if left_norm == 0 or right_norm == 0:
        raise ValueError("Cannot compare zero-length vectors.")

    # Calculate the dot product.
    dot_product = sum(
        left_value * right_value
        for left_value, right_value in zip(
            left,
            right,
            strict=True,
        )
    )

    return dot_product / (left_norm * right_norm)


class AnswerCorrectnessEvaluator:
    """
    Calculates semantic similarity between a generated answer
    and a reference answer.
    """

    def __init__(
        self,
        embedding_service,
    ):
        """
        Initialize the evaluator.

        Args:
            embedding_service:
                Existing embedding service used to convert
                both answers into embedding vectors.
        """

        self.embedding_service = embedding_service

    def evaluate(
        self,
        answer: str,
        reference_answer: str,
    ) -> float:
        """
        Calculate semantic similarity between two answers.

        Args:
            answer:
                Answer generated by DocsQuery.

            reference_answer:
                Human-written reference answer.

        Returns:
            Cosine similarity score.
        """

        # An empty generated answer cannot be considered correct.
        if not answer.strip():
            return 0.0

        # No reference answer means there is nothing to compare.
        if not reference_answer.strip():
            return 0.0

        # Embed both pieces of text using the existing embedding
        # service rather than introducing another embedding model.
        vectors = self.embedding_service.embed_texts(
            [
                answer,
                reference_answer,
            ]
        )

        return cosine_similarity(
            vectors[0],
            vectors[1],
        )
